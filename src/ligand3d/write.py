def write_trajectory(
    path: str | Path,
    mol: Chem.Mol,
    frames: list,
    resname: str = "LIG",
    energies: list[float] | None = None,
    stage_labels: list[str] | None = None,
) -> Path:
    """Write the optimizer path as a multi-model PDB.

    One MODEL per step, in order, so the file animates in PyMOL, ChimeraX, or
    VMD. Energies and the method responsible for each frame go into REMARKs
    rather than being lost, because a trajectory whose frames you cannot label
    is much less useful than one you can.
    """
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    if not frames:
        raise ValueError("no frames to write")

    from rdkit.Geometry import Point3D

    named = assign_pdb_names(mol, resname=resname)
    template = Chem.Mol(named)
    template.RemoveAllConformers()
    base = Chem.Conformer(named.GetConformer(named.GetConformers()[0].GetId()))
    template.AddConformer(base, assignId=True)
    conf = template.GetConformer(0)

    stamp = _dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        "REMARK   1 LIGAND3D MINIMIZATION TRAJECTORY",
        f"REMARK   1 DATE {stamp}",
        f"REMARK   1 {len(frames)} FRAMES, ONE PER OPTIMIZER STEP"[:80],
    ]
    if stage_labels:
        for label in dict.fromkeys(stage_labels):
            lines.append(f"REMARK   1 METHOD {label}"[:80])

    conect: list[str] = []
    for index, positions in enumerate(frames, start=1):
        for i, (x, y, z) in enumerate(positions):
            conf.SetAtomPosition(i, Point3D(float(x), float(y), float(z)))
        with rdkit_quiet():
            block = Chem.MolToPDBBlock(template, confId=0, flavor=0)
        if not conect:
            conect = [ln for ln in block.splitlines() if ln.startswith("CONECT")]

        header = f"MODEL     {index:4d}"
        lines.append(header)
        if energies is not None and index - 1 < len(energies):
            label = stage_labels[index - 1] if stage_labels and index - 1 < len(stage_labels) else ""
            lines.append(
                f"REMARK   2 FRAME {index:5d} ENERGY {energies[index - 1]:16.6f} {label}"[:80]
            )
        lines.extend(
            ln for ln in block.splitlines() if ln.startswith(("ATOM", "HETATM"))
        )
        lines.append("ENDMDL")

    lines.extend(conect)
    lines.append("END")
    p.write_text("\n".join(lines) + "\n")
    return p
