_CIF_BOND_ORDER = {
    Chem.BondType.SINGLE: "SING",
    Chem.BondType.DOUBLE: "DOUB",
    Chem.BondType.TRIPLE: "TRIP",
    Chem.BondType.QUADRUPLE: "QUAD",
    Chem.BondType.AROMATIC: "SING",  # value_order with aromatic_flag Y
}


def cif_available() -> bool:
    """True if gemmi is importable, which is what does the mmCIF conversion."""
    import importlib.util

    return importlib.util.find_spec("gemmi") is not None


def to_cif_string(
    mol: Chem.Mol,
    records: list[ConformerRecord] | None = None,
    resname: str = "LIG",
    smiles: str | None = None,
    name: str = "ligand3d",
    extra_remarks: list[str] | None = None,
) -> str:
    """Render conformers as mmCIF.

    Coordinates go through gemmi, which produces a standard `_atom_site` loop
    with `pdbx_PDB_model_num` distinguishing conformers — the same convention a
    multi-model PDB uses, and what structural tools expect.

    A `_chem_comp_bond` loop is appended with bond orders and aromatic flags.
    That is the one thing PDB genuinely cannot carry, so including it here makes
    the mmCIF self-sufficient rather than needing the SDF sidecar to be read
    alongside it.
    """
    try:
        import gemmi
    except ImportError as exc:  # pragma: no cover - guarded by cif_available
        from .errors import Ligand3DError

        raise Ligand3DError(
            "writing mmCIF needs gemmi. Install it with: pip install gemmi"
        ) from exc

    named = assign_pdb_names(mol, resname=resname)
    smiles = smiles or Chem.MolToSmiles(Chem.RemoveHs(named))

    pdb_block = to_pdb_block(
        named, records=records, resname=resname, smiles=smiles,
        extra_remarks=extra_remarks,
    )
    structure = gemmi.read_pdb_string(pdb_block)
    # Without a name, gemmi labels the entry "string" after its input.
    structure.name = name
    structure.setup_entities()

    document = structure.make_mmcif_document()
    block = document.sole_block()

    _add_bond_loop(block, named, resname=resname)
    _add_provenance(block, smiles=smiles, records=records)

    return document.as_string()


def _add_bond_loop(block, mol: Chem.Mol, resname: str) -> None:
    """Append `_chem_comp_bond`, the bond orders PDB cannot represent."""
    comp = (resname or "LIG").upper()[:_MAX_RESNAME]
    names = [
        atom.GetMonomerInfo().GetName().strip()
        if atom.GetMonomerInfo() is not None
        else f"{atom.GetSymbol()}{atom.GetIdx()}"
        for atom in mol.GetAtoms()
    ]

    loop = block.init_loop(
        "_chem_comp_bond.",
        ["comp_id", "atom_id_1", "atom_id_2", "value_order", "pdbx_aromatic_flag"],
    )
    for bond in mol.GetBonds():
        order = _CIF_BOND_ORDER.get(bond.GetBondType(), "SING")
        aromatic = "Y" if bond.GetIsAromatic() else "N"
        loop.add_row(
            [comp, names[bond.GetBeginAtomIdx()], names[bond.GetEndAtomIdx()],
             order, aromatic]
        )


def _add_provenance(block, smiles: str, records: list[ConformerRecord] | None) -> None:
    """Record what produced this file, the way the PDB REMARKs do."""
    from . import __version__

    stamp = _dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        f"Generated by ligand3d {__version__} on {stamp}",
        f"SMILES {smiles}",
    ]
    if records and records[0].energy is not None:
        first = records[0]
        kind = "total electronic" if first.energy_kind == "total" else "strain"
        lines.append(
            f"{kind} energies from {first.backend} in {first.energy_unit}; "
            "only differences between conformers of this molecule are meaningful"
        )
        for n, record in enumerate(records, start=1):
            if record.energy is not None:
                lines.append(f"model {n} energy {record.energy:.6f}")

    loop = block.init_loop("_ligand3d.", ["ordinal", "detail"])
    for n, line in enumerate(lines, start=1):
        loop.add_row([str(n), gemmi_quote(line)])


def gemmi_quote(text: str) -> str:
    """Quote a CIF value that contains spaces."""
    if not text:
        return "?"
    if any(ch in text for ch in " \t'\"") or text[0] in "_#$[]":
        escaped = text.replace("'", "\\'")
        return f"'{escaped}'"
    return text


def write_cif(
    path: str | Path,
    mol: Chem.Mol,
    records: list[ConformerRecord] | None = None,
    resname: str = "LIG",
    smiles: str | None = None,
    extra_remarks: list[str] | None = None,
) -> Path:
    """Write an mmCIF file and return its path."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(
        to_cif_string(
            mol, records=records, resname=resname, smiles=smiles,
            name=p.stem, extra_remarks=extra_remarks,
        )
    )
    return p


def verify_cif_roundtrip(path: str | Path, reference: Chem.Mol) -> None:
    """Confirm the mmCIF we wrote parses and holds the right atoms."""
    from .errors import Ligand3DError

    try:
        import gemmi
    except ImportError:  # pragma: no cover
        return
    try:
        structure = gemmi.read_structure(str(path))
    except Exception as exc:
        raise Ligand3DError(f"wrote {path} but gemmi cannot read it back: {exc}") from exc
    if len(structure) == 0:
        raise Ligand3DError(f"{path} contains no models")
    n_atoms = sum(len(residue) for chain in structure[0] for residue in chain)
    if n_atoms != reference.GetNumAtoms():
        raise Ligand3DError(
            f"wrote {path} with {reference.GetNumAtoms()} atoms but it reads back "
            f"as {n_atoms}"
        )


